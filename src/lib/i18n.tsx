type Dict = {
  [K in keyof typeof dict.fr]: (typeof dict.fr)[K] extends readonly string[]
    ? readonly string[]
    : (typeof dict.fr)[K] extends readonly { title: string; body: string }[]
      ? readonly { title: string; body: string }[]
      : (typeof dict.fr)[K] extends Record<string, string>
        ? Record<string, string>
        : string;
};

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Dict }>({
  lang: "fr",
  setLang: () => {},
  t: dict.fr,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");
  const langRef = useRef<Lang>("fr");
  langRef.current = lang;
  // Vrai dès qu'un ?hl explicite a été vu : il prime sur la préférence du compte.
  const explicitRef = useRef(false);
  // Chaque navigation (client) change location : on garde ?hl synchronisé.
  const location = useRouterState({ select: (s) => s.location });

  // Persistance de la langue sur le profil connecté (best-effort, sans bloquer l'UI).
  const saveToProfile = async (l: Lang) => {
    try {
      const { supabase } = await import("@/integrations/supabase/client");
      const { data } = await supabase.auth.getSession();
      const uid = data.session?.user?.id;
      if (!uid) return;
      await supabase.from("profiles").update({ ui_lang: l }).eq("id", uid);
    } catch {
      /* hors-ligne ou non connecté : la préférence locale suffit */
    }
  };

  const writeHlParam = (l: Lang) => {
    if (typeof window === "undefined") return;
    const url = new URL(window.location.href);
    if (url.searchParams.get("hl") === l) return;
    url.searchParams.set("hl", l);
    // replaceState : on garde ?hl visible sans relancer de navigation ni casser l'historique.
    window.history.replaceState(window.history.state, "", url.pathname + url.search + url.hash);
  };

  useEffect(() => {
    if (typeof window === "undefined") return;
    const apply = () => {
      // 1) ?hl= dans l'URL (version indexable par les moteurs), 2) préférence stockée.
      const fromUrl = new URLSearchParams(window.location.search).get("hl");
      if (fromUrl === "fr" || fromUrl === "en") {
        explicitRef.current = true;
        if (fromUrl !== langRef.current) setLangState(fromUrl);
        localStorage.setItem("alesim.lang", fromUrl);
        return;
      }
      // Pas de ?hl (navigation interne, lien partagé sans param) : on réapplique le choix.
      const stored = localStorage.getItem("alesim.lang") as Lang | null;
      const next: Lang = stored === "fr" || stored === "en" ? stored : langRef.current;
      if (next !== langRef.current) setLangState(next);
      writeHlParam(next);
    };
    apply();
    // Le routeur peut réécrire l'URL juste après la navigation : on repasse au tick suivant.
    const id = window.setTimeout(apply, 0);
    return () => window.clearTimeout(id);
  }, [location.href]);

  // Au chargement (et à chaque changement de session), on réapplique la langue du profil.
  useEffect(() => {
    if (typeof window === "undefined") return;
    let cancelled = false;
    let unsub: (() => void) | undefined;

    const applyFromProfile = async (userId: string | undefined) => {
      if (!userId) return;
      const { supabase } = await import("@/integrations/supabase/client");
      const { data } = await supabase
        .from("profiles")
        .select("ui_lang")
        .eq("id", userId)
        .maybeSingle();
      const remote = data?.ui_lang;
      if (cancelled || (remote !== "fr" && remote !== "en")) return;
      if (explicitRef.current) {
        // L'utilisateur a choisi explicitement via ?hl : on aligne le compte dessus.
        if (remote !== langRef.current) void saveToProfile(langRef.current);
        return;
      }
      if (remote !== langRef.current) setLangState(remote);
      localStorage.setItem("alesim.lang", remote);
      writeHlParam(remote);
    };

    void (async () => {
      const { supabase } = await import("@/integrations/supabase/client");
      const { data } = await supabase.auth.getSession();
      await applyFromProfile(data.session?.user?.id);
      if (cancelled) return;
      const { data: sub } = supabase.auth.onAuthStateChange((event, session) => {
        if (event === "SIGNED_IN" || event === "USER_UPDATED") {
          void applyFromProfile(session?.user?.id);
        }
      });
      unsub = () => sub.subscription.unsubscribe();
    })();

    return () => {
      cancelled = true;
      unsub?.();
    };
  }, []);

  // <html lang> suit toujours la langue réellement affichée.
  useEffect(() => {
    if (typeof document !== "undefined") document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window === "undefined") return;
    explicitRef.current = true;
    localStorage.setItem("alesim.lang", l);
    writeHlParam(l);
    void saveToProfile(l);
  };

  return (
    <LangContext.Provider value={{ lang, setLang, t: dict[lang] }}>{children}</LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}
